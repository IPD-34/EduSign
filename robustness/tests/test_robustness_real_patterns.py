"""
test_robustness_real_patterns.py

Re-runs the Month 1 robustness suite's core assertions (no NaN/Inf where
they shouldn't be, no discontinuous jumps introduced by filling) against
samples generated by robustness.synthetic.generate_realistic_dropout --
i.e. against the REAL per-channel run-length and co-occurrence
distributions measured from the 41 actual ASLLRP train+val samples
(data/real_dropout_stats.json), instead of the arbitrary per-frame
dropout probabilities test_hold_last_value.py / test_normalisation.py
use via make_synthetic_sample.

This file is purely additive: it does not modify or weaken
test_hold_last_value.py or test_normalisation.py, and does not touch
make_synthetic_sample. It exists to answer one question: does anything
in hold_last_value.py or normalisation.py break under dropout shapes the
original hand-picked synthetic probabilities/patterns didn't happen to
cover (e.g. left_hand's real ~22-frame burst, or the ~35% real rate of
multiple channels dropping out at the same time)?

Coverage strategy: parametrized over multiple seeds AND multiple
sequence lengths spanning the real samples' actual range (roughly 80-400
frames; see the real per-channel run-length max values in
data/real_dropout_stats.json), so the long tail of real burst lengths
(e.g. left_hand's ~22-frame burst) has room to actually occur within the
generated sequence, not just at the sample-mean scale.
"""

from __future__ import annotations

import numpy as np
import pytest

from robustness.hold_last_value import compute_fill_validity, hold_last_value_sample
from robustness.normalisation import normalize_landmarks_sample
from robustness.synthetic import _load_real_stats, generate_realistic_dropout

_GROUPS = ("pose", "left_hand", "right_hand", "face")

_REAL_STATS_PATH = "data/real_dropout_stats.json"

# Sequence lengths spanning the real samples' actual range (shortest ~80,
# longest ~400 frames), plus a short one to stress-test edge behavior
# when a real burst length would exceed the sequence itself.
_SEQUENCE_LENGTHS = [40, 80, 158, 300]
_SEEDS = [0, 1, 2, 3, 4]


def _real_stats_available() -> bool:
    from pathlib import Path

    return Path(_REAL_STATS_PATH).exists()


pytestmark = pytest.mark.skipif(
    not _real_stats_available(),
    reason=(
        f"{_REAL_STATS_PATH} not found -- run "
        "`uv run python -m scripts.extract_real_dropout_stats` first."
    ),
)


@pytest.fixture(scope="module")
def real_stats():
    return _load_real_stats(_REAL_STATS_PATH)


def _reference_forward_fill(
    landmarks: np.ndarray, presence: np.ndarray, max_hold_frames=None
) -> np.ndarray:
    """
    Independent (not reusing hold_last_value.py's internals) reference
    implementation of "hold the last valid value," used as an oracle to
    check hold_last_value_sample doesn't introduce a discontinuous /
    wrong-value jump under the real dropout patterns -- filled frames
    must equal exactly the most recent valid frame's value, nothing else.
    """
    out = landmarks.copy()
    last_valid = None
    hold = 0
    for t in range(landmarks.shape[0]):
        if presence[t]:
            last_valid = landmarks[t].copy()
            hold = 0
        elif last_valid is not None:
            hold += 1
            if max_hold_frames is None or hold <= max_hold_frames:
                out[t] = last_valid
    return out


# ---------------------------------------------------------------------
# generate_realistic_dropout itself: sanity on the generator's contract
# ---------------------------------------------------------------------


@pytest.mark.parametrize("num_frames", _SEQUENCE_LENGTHS)
@pytest.mark.parametrize("seed", _SEEDS)
def test_generate_realistic_dropout_shapes_and_dtypes(num_frames, seed):
    sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)

    assert sample.pose.shape == (num_frames, 33, 4)
    assert sample.left_hand.shape == (num_frames, 21, 3)
    assert sample.right_hand.shape == (num_frames, 21, 3)
    assert sample.face.shape == (num_frames, 478, 3)
    for group in _GROUPS:
        assert getattr(sample.presence, group).shape == (num_frames,)
        assert getattr(sample.presence, group).dtype == bool


def test_generate_realistic_dropout_is_deterministic_given_seed():
    a = generate_realistic_dropout(num_frames=100, seed=42)
    b = generate_realistic_dropout(num_frames=100, seed=42)

    np.testing.assert_array_equal(a.pose, b.pose)
    np.testing.assert_array_equal(a.presence.left_hand, b.presence.left_hand)


def test_generate_realistic_dropout_missing_frames_are_zero_filled():
    sample = generate_realistic_dropout(num_frames=200, seed=7)

    for group in _GROUPS:
        presence = getattr(sample.presence, group)
        landmarks = getattr(sample, group)
        missing = ~presence
        if missing.any():
            assert np.all(landmarks[missing] == 0.0)


def test_generate_realistic_dropout_missing_fraction_roughly_matches_real_stats(real_stats):
    # Not an exact match (bootstrap resampling + rounding to whole bursts),
    # but should land in the right ballpark across many seeds -- a gross
    # mismatch here would mean the generator isn't actually tracking the
    # real per-channel target fraction.
    num_frames = 300
    per_channel_fractions = {g: [] for g in _GROUPS}
    for seed in range(20):
        sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)
        for group in _GROUPS:
            presence = getattr(sample.presence, group)
            per_channel_fractions[group].append(1.0 - presence.mean())

    for group in _GROUPS:
        real_fraction = real_stats["per_channel"][group]["fraction_missing"]
        observed_mean = float(np.mean(per_channel_fractions[group]))
        # Generous absolute tolerance: this is a ballpark sanity check on
        # the targeting mechanism, not a precision requirement.
        assert observed_mean == pytest.approx(real_fraction, abs=0.03), (
            f"{group}: real fraction_missing={real_fraction:.4f}, "
            f"generator's mean over 20 seeds={observed_mean:.4f}"
        )


