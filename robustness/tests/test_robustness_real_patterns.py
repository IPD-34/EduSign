@pytest.mark.parametrize("num_frames", _SEQUENCE_LENGTHS)
@pytest.mark.parametrize("seed", _SEEDS)
def test_hold_last_value_no_nan_or_inf_under_realistic_dropout(num_frames, seed):
    sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)

    out = hold_last_value_sample(sample, max_hold_frames=None)

    for group in _GROUPS:
        arr = getattr(out, group)
        assert np.all(np.isfinite(arr)), (
            f"{group}: non-finite value found after hold-last-value "
            f"(num_frames={num_frames}, seed={seed})"
        )


@pytest.mark.parametrize("num_frames", _SEQUENCE_LENGTHS)
@pytest.mark.parametrize("seed", _SEEDS)
def test_hold_last_value_no_discontinuous_jump_under_realistic_dropout(num_frames, seed):
    """
    'No discontinuous jump': every filled frame must equal exactly the
    most recent valid frame's value (per the independent reference
    forward-fill above) -- not some other, wrong value. Checked for
    every group, under real burst-length/co-occurrence patterns, not
    just the hand-picked cases in test_hold_last_value.py.
    """
    sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)

    out = hold_last_value_sample(sample, max_hold_frames=None)

    for group in _GROUPS:
        landmarks = getattr(sample, group)
        presence = getattr(sample.presence, group)
        expected = _reference_forward_fill(landmarks, presence, max_hold_frames=None)
        actual = getattr(out, group)

        np.testing.assert_array_equal(
            actual, expected,
            err_msg=f"{group}: hold-last-value output diverged from the "
                    f"reference forward-fill (num_frames={num_frames}, seed={seed})",
        )


@pytest.mark.parametrize("num_frames", _SEQUENCE_LENGTHS)
@pytest.mark.parametrize("seed", _SEEDS)
@pytest.mark.parametrize("max_hold_frames", [None, 5, 0])
def test_hold_last_value_respects_hold_budget_under_realistic_dropout(num_frames, seed, max_hold_frames):
    sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)

    out = hold_last_value_sample(sample, max_hold_frames=max_hold_frames)

