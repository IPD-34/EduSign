@pytest.mark.parametrize("num_frames", _SEQUENCE_LENGTHS)
@pytest.mark.parametrize("seed", _SEEDS)
def test_pipeline_hold_then_normalize_no_inf_under_realistic_dropout(num_frames, seed):
    """
    UPDATED: this test used to call normalize_landmarks_sample(filled)
    with no face_validity, which is the exact composition that turned out
    to have a real bug -- normalize_landmarks_sample decided validity from
    presence alone, so a frame hold_last_value_sample just filled with a
    real, carried-forward value was still marked NaN (presence is, by
    design, never changed by hold-last-value). On real ASLLRP data this
    poisoned 31/41 samples down to 100% NaN model output via self-attention
    mixing (src/models/dataset.py, which composes these two exactly this
    way, is what surfaced it).

    Fixed via hold_last_value.compute_fill_validity() +
    normalize_landmarks_sample's face_validity parameter -- this test now
    exercises the SAME composition src/models/dataset.py actually uses, not
    the pre-fix one. The no-inf assertion below is unchanged (still a real,
    still-required property); what changed is that face_validity is now
    threaded through, matching real usage.
    """
    sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)

    filled = hold_last_value_sample(sample, max_hold_frames=None)
    face_validity = compute_fill_validity(sample.presence.face, max_hold_frames=None)
    out = normalize_landmarks_sample(filled, face_validity=face_validity)

    for group in _GROUPS:
        arr = getattr(out, group)
        assert np.all(np.isnan(arr) | np.isfinite(arr)), (
            f"{group}: +/-inf found after hold-last-value + normalisation "
            f"(num_frames={num_frames}, seed={seed})"
        )


@pytest.mark.parametrize("num_frames", _SEQUENCE_LENGTHS)
@pytest.mark.parametrize("seed", _SEEDS)
def test_pipeline_face_validity_never_produces_more_nan_than_presence_only(num_frames, seed):
    """
    Regression coverage for the fix itself: using face_validity (post-fill)
    must never produce MORE NaN frames than the old presence-only
    composition did, and on any sample with real face dropout that
    hold-last-value could actually fill, it should produce STRICTLY FEWER
    -- confirming the fix has a real, measurable effect on real-pattern
    data, not just the one hand-built case in test_normalisation.py.
    """
    sample = generate_realistic_dropout(num_frames=num_frames, seed=seed)
    filled = hold_last_value_sample(sample, max_hold_frames=None)
    face_validity = compute_fill_validity(sample.presence.face, max_hold_frames=None)

    out_old_composition = normalize_landmarks_sample(filled)  # pre-fix behavior, still reachable
    out_fixed = normalize_landmarks_sample(filled, face_validity=face_validity)

    old_valid = ~np.isnan(out_old_composition.pose[:, 0, 0])
    fixed_valid = ~np.isnan(out_fixed.pose[:, 0, 0])

    assert fixed_valid.sum() >= old_valid.sum(), (
        f"num_frames={num_frames}, seed={seed}: face_validity composition "
        f"covered FEWER valid frames ({fixed_valid.sum()}) than the old "
        f"presence-only composition ({old_valid.sum()}) -- the fix must "
        f"never regress coverage."
    )

    # A frame that hold-last-value could fill but presence-only normalize
    # would have NaN'd is exactly (face_validity True) & (original face
    # presence False) -- if any such frame exists in this sample, the fix
    # must have actually rescued at least one of them.
    rescuable = face_validity & ~sample.presence.face
    if rescuable.any():
        assert fixed_valid.sum() > old_valid.sum(), (
            f"num_frames={num_frames}, seed={seed}: {rescuable.sum()} "
            f"rescuable frame(s) existed but coverage did not improve"
        )
