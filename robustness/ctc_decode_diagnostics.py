"""
ctc_decode_diagnostics.py

One-off diagnostic script for the 0/21 exact-match rate reported by
robustness/confidence_baseline.py against checkpoints/month2_asllrp/best_val.pt.
NOT part of the shipped confidence-estimation code -- this exists to answer
one question: is the 0/21 rate caused by a bug in ctc_greedy_decode's
collapse logic, or by the model itself (step 4000, early-stopped,
val_loss=5.50, not converged) not yet emitting useful non-blank predictions?

Two things this script does, using robustness/confidence_baseline_report.json
(already generated by confidence_baseline.py's CLI -- not regenerated here):

1. For all 21 utterances: decode target and CTC-greedy-decoded token ids
   back to readable strings via data/vocab_merged.json, print them side by
   side with lengths, and bucket each utterance into one of:
     a) EMPTY / all-blank decode
     b) non-empty but short/degenerate (decoded len << target len)
     c) similar length, wrong tokens (genuine recognition failure)
     d) decoded LONGER than target, or repeated/looping tokens (possible
        ctc_greedy_decode collapse bug)

2. Re-runs the model on 3 sample val utterances to print the RAW
   per-timestep argmax token id sequence (pre-collapse) alongside the
   fraction that is the blank token -- if that fraction is very high,
   it confirms the model itself (not the decode logic) is the cause.

Usage:
    uv run python -m robustness.ctc_decode_diagnostics
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import torch
from torch.utils.data import DataLoader

from robustness.confidence_baseline import (
    DEFAULT_ASLLRP_TOKEN_TO_ID_PATH,
    DEFAULT_CHECKPOINT_PATH,
    DEFAULT_VAL_NPZ_DIR,
    DEFAULT_VOCAB_PATH,
    _load_model,
)
from src.models.combined_loss import reorder_valid_frames_first
from src.models.dataset import SignLanguageDataset, collate_fn

REPORT_PATH = "robustness/confidence_baseline_report.json"
NUM_RAW_SAMPLES = 3
TRAIN_NPZ_DIR = "data/processed/asllrp/train"


def _tokens_to_str(ids: list[int], id_to_token: dict) -> list[str]:
    return [id_to_token.get(i, f"<UNK_ID_{i}>") for i in ids]


def _is_degenerate(decoded: list[int]) -> str | None:
    """Returns a short tag describing an obvious degeneracy, or None."""
    if len(decoded) == 0:
        return "EMPTY"
    if len(set(decoded)) == 1:
        return f"SINGLE_TOKEN_REPEATED(x{len(decoded)})"
    return None


def categorize(decoded: list[int], target: list[int]) -> str:
    """
    Buckets per the investigation's four categories:
      a) EMPTY
      b) SHORT/DEGENERATE (non-empty but len(decoded) << len(target))
      c) SIMILAR_LENGTH_WRONG (comparable length, wrong tokens)
      d) LONGER_OR_LOOPING
    """
    if len(decoded) == 0:
        return "a) EMPTY/all-blank"

    if len(decoded) > len(target):
        return "d) LONGER_than_target"

    # "similar length" defined as within 1 token, or at least half of target's
    # length for longer targets -- anything shorter than that counts as
    # degenerate/short rather than a genuine same-length wrong-token failure.
    if len(decoded) >= max(1, len(target) - 1) and len(decoded) >= (len(target) + 1) // 2:
        return "c) SIMILAR_LENGTH_wrong_tokens"

    return "b) SHORT/degenerate"


def print_side_by_side_report(report: dict, id_to_token: dict) -> Counter:
    buckets = Counter()
    print("=== Per-utterance target vs. CTC-greedy-decoded (all utterances) ===")
    for u in report["per_utterance"]:
        target = u["target"]
        decoded = u["ctc_greedy_decoded"]
        bucket = categorize(decoded, target)
        buckets[bucket] += 1
        degeneracy = _is_degenerate(decoded)

        print(f"\nvideo_id={u['video_id']}  bucket={bucket}"
              + (f"  degenerate={degeneracy}" if degeneracy else ""))
        print(f"  target  (len={len(target):2d}): {_tokens_to_str(target, id_to_token)}")
        print(f"  decoded (len={len(decoded):2d}): {_tokens_to_str(decoded, id_to_token)}")

    return buckets


def print_bucket_summary(buckets: Counter, total: int) -> None:
    print("\n=== Bucket summary ===")
    for key in sorted(buckets):
        print(f"  {key}: {buckets[key]}/{total}")


@torch.no_grad()
def print_raw_argmax_samples(
    checkpoint_path: str,
    val_npz_dir: str,
    vocab_path: str,
    asllrp_token_to_id_path: str,
    id_to_token: dict,
    num_samples: int,
) -> None:
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = _load_model(checkpoint_path, vocab_path, device)

    with open(vocab_path, "r", encoding="utf-8") as f:
        vocab_merged = json.load(f)
    blank_id = len(vocab_merged)
    id_to_token = dict(id_to_token)
    id_to_token[blank_id] = "<BLANK>"

    val_dataset = SignLanguageDataset(
        npz_dir=val_npz_dir, vocab_path=vocab_path,
        asllrp_token_to_id_path=asllrp_token_to_id_path,
    )
    val_loader = DataLoader(val_dataset, batch_size=1, collate_fn=collate_fn, shuffle=False)

    model.eval()
    print(f"\n=== Raw per-timestep argmax (pre-collapse), {num_samples} sample utterances ===")
    print(f"(blank_id = {blank_id})")

    shown = 0
    for batch in val_loader:
        if shown >= num_samples:
            break
        landmarks = batch["landmarks"].to(device)
        enc_mask = batch["encoder_attention_mask"].to(device)

        ctc_log_probs, _ = model.forward_ctc_and_boundary(landmarks, enc_mask)
        # mask.sum()-length PREFIX slice (ctc_log_probs[0, :valid_len]) silently
        # assumes valid frames start at index 0 -- broken once a sample can carry
        # a leading-dropout invalid frame (see src/models/dataset.py). Reuse the
        # same reorder_valid_frames_first fix already applied to the CTC training
        # loss and to confidence_baseline.ctc_greedy_decode, instead of reading a
        # shifted window here too.
        valid_len = int(enc_mask.sum(dim=1).item())
        reordered = reorder_valid_frames_first(ctc_log_probs, enc_mask)[0]
        argmax_ids = reordered[:valid_len].argmax(dim=-1).tolist()

        blank_count = sum(1 for t in argmax_ids if t == blank_id)
        blank_fraction = blank_count / len(argmax_ids)

        print(f"\nvideo_id={batch['video_ids'][0]}  valid_timesteps={valid_len}  "
              f"blank_fraction={blank_fraction:.3f}")
        print(f"  raw argmax ids   : {argmax_ids}")
        print(f"  raw argmax tokens: {_tokens_to_str(argmax_ids, id_to_token)}")

        shown += 1


@torch.no_grad()
def blank_fraction_over_all_samples(
    checkpoint_path: str,
    npz_dirs: dict,
    vocab_path: str,
    asllrp_token_to_id_path: str,
) -> list[dict]:
    """
    Runs the model over EVERY sample in each of npz_dirs (a {split_name:
    dir_path} mapping, e.g. {"train": ..., "val": ...}) and records each
    sample's blank-prediction fraction (argmax == blank_id, over valid
    timesteps only). Prints the full per-sample table (not just a
    mean/median) plus a train-vs-val breakdown, and flags whether the
    blank-collapse finding (previously checked on only 3 val samples) is
    absolute across all samples or has any real gradient/outlier.
    """
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = _load_model(checkpoint_path, vocab_path, device)

    with open(vocab_path, "r", encoding="utf-8") as f:
        vocab_merged = json.load(f)
    blank_id = len(vocab_merged)

    model.eval()
    results = []
    for split_name, npz_dir in npz_dirs.items():
        dataset = SignLanguageDataset(
            npz_dir=npz_dir, vocab_path=vocab_path,
            asllrp_token_to_id_path=asllrp_token_to_id_path,
        )
        loader = DataLoader(dataset, batch_size=1, collate_fn=collate_fn, shuffle=False)
        for batch in loader:
            landmarks = batch["landmarks"].to(device)
            enc_mask = batch["encoder_attention_mask"].to(device)

            ctc_log_probs, _ = model.forward_ctc_and_boundary(landmarks, enc_mask)
            # Same fix as print_raw_argmax_samples above -- select via the actual
            # mask positions (reorder_valid_frames_first), not a mask.sum()-length
            # prefix slice.
            valid_len = int(enc_mask.sum(dim=1).item())
            reordered = reorder_valid_frames_first(ctc_log_probs, enc_mask)[0]
            argmax_ids = reordered[:valid_len].argmax(dim=-1).tolist()

            blank_count = sum(1 for t in argmax_ids if t == blank_id)
            blank_fraction = blank_count / len(argmax_ids)

            results.append({
                "video_id": batch["video_ids"][0],
                "split": split_name,
                "valid_timesteps": valid_len,
                "blank_fraction": blank_fraction,
            })

    return results


def print_blank_fraction_report(results: list[dict]) -> None:
    import statistics

    ordered = sorted(results, key=lambda r: r["blank_fraction"])

    print(f"\n=== Blank-prediction fraction across all {len(ordered)} samples (train + val) ===")
    print(f"{'video_id':<16} {'split':<6} {'T':>5} {'blank_fraction':>14}")
    for r in ordered:
        print(f"{r['video_id']:<16} {r['split']:<6} {r['valid_timesteps']:>5} "
              f"{r['blank_fraction']:>14.4f}")

    fractions = [r["blank_fraction"] for r in results]
    train_fractions = [r["blank_fraction"] for r in results if r["split"] == "train"]
    val_fractions = [r["blank_fraction"] for r in results if r["split"] == "val"]

    print(f"\nn={len(fractions)}  min={min(fractions):.4f}  max={max(fractions):.4f}  "
          f"mean={statistics.mean(fractions):.4f}  median={statistics.median(fractions):.4f}")
    print(f"train (n={len(train_fractions)}): mean={statistics.mean(train_fractions):.4f}  "
          f"min={min(train_fractions):.4f}")
    print(f"val   (n={len(val_fractions)}): mean={statistics.mean(val_fractions):.4f}  "
          f"min={min(val_fractions):.4f}")

    threshold = 0.99
    below = [r for r in ordered if r["blank_fraction"] < threshold]
    print(f"\nSamples below {threshold:.0%} blank: {len(below)}/{len(ordered)}")
    for r in below:
        print(f"  {r['video_id']} ({r['split']}): {r['blank_fraction']:.4f}")

    absolute = all(r["blank_fraction"] >= 0.90 for r in ordered)
    print(
        f"\nVerdict: blank-collapse is {'ABSOLUTE' if absolute else 'NOT absolute'} "
        f"across all {len(ordered)} samples -- every sample sits at or above "
        f"{min(fractions):.1%} blank, {'no' if absolute else 'a'} sample breaks the pattern "
        f"in a way that would materially change the Person C report."
    )


def main() -> None:
    with open(DEFAULT_VOCAB_PATH, "r", encoding="utf-8") as f:
        vocab_merged = json.load(f)
    id_to_token = {v: k for k, v in vocab_merged.items()}

    if not Path(REPORT_PATH).exists():
        raise RuntimeError(
            f"{REPORT_PATH} not found -- run "
            "`python -m robustness.confidence_baseline --output-json "
            f"{REPORT_PATH}` first."
        )
    with open(REPORT_PATH, "r", encoding="utf-8") as f:
        report = json.load(f)

    buckets = print_side_by_side_report(report, id_to_token)
    print_bucket_summary(buckets, total=report["num_utterances"])

    print_raw_argmax_samples(
        DEFAULT_CHECKPOINT_PATH,
        DEFAULT_VAL_NPZ_DIR,
        DEFAULT_VOCAB_PATH,
        DEFAULT_ASLLRP_TOKEN_TO_ID_PATH,
        id_to_token,
        NUM_RAW_SAMPLES,
    )

    all_sample_results = blank_fraction_over_all_samples(
        DEFAULT_CHECKPOINT_PATH,
        {"train": TRAIN_NPZ_DIR, "val": DEFAULT_VAL_NPZ_DIR},
        DEFAULT_VOCAB_PATH,
        DEFAULT_ASLLRP_TOKEN_TO_ID_PATH,
    )
    print_blank_fraction_report(all_sample_results)


if __name__ == "__main__":
    main()
